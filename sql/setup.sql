-- Data is private: each signed-in user can access only their own rows.

create table if not exists public.clothing_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null,
  brand text default '',
  colour text default '',
  style text default '',
  size text default '',
  weight text default '',
  has_zip boolean,
  last_worn text default '',
  season text default '',
  image_data text default ''
);

create index if not exists clothing_items_user_id_idx
  on public.clothing_items(user_id);

create table if not exists public.style_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  formal boolean not null default true,
  heat boolean not null default true,
  notes text not null default ''
);

alter table public.clothing_items enable row level security;
alter table public.style_preferences enable row level security;

-- Anonymous visitors have no access to anyone's wardrobe or preferences.
revoke all on public.clothing_items from anon;
revoke all on public.style_preferences from anon;
grant select, insert, update, delete on public.clothing_items to authenticated;
grant select, insert, update, delete on public.style_preferences to authenticated;
grant usage, select on sequence public.clothing_items_id_seq to authenticated;

-- Clothing: explicit policies for SELECT, INSERT, UPDATE and DELETE.
create policy "Read own clothes" on public.clothing_items
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Add own clothes" on public.clothing_items
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Edit own clothes" on public.clothing_items
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Delete own clothes" on public.clothing_items
  for delete to authenticated using ((select auth.uid()) = user_id);

-- Preferences: each user may view and change only their own settings.
create policy "Read own settings" on public.style_preferences
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Add own settings" on public.style_preferences
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Edit own settings" on public.style_preferences
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Delete own settings" on public.style_preferences
  for delete to authenticated using ((select auth.uid()) = user_id);
